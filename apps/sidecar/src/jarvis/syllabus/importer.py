"""Build the syllabus ontology YAML from the owner-supplied syllabus Markdown (datasets/syllabus).

Run:  python -m jarvis.syllabus.importer <syllabus.md> <out_dir>
Node titles are the document's own text; only whitespace and the listed spelling fixes are changed.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

# Spelling mistakes of the source document, corrected in node titles only (the dataset Markdown stays as is).
TYPO_FIXES = {
    "Durkhteim": "Durkheim",
    "Talcolt": "Talcott",
    "G.S. Ghure": "G.S. Ghurye",
    "func tionalist": "functionalist",
    "fundamen talism": "fundamentalism",
    "Contem porary": "Contemporary",
    "oflabour": "of labour",
    "scope’ and": "scope and",
}

HEADER = """# Generated by `python -m jarvis.syllabus.importer` from datasets/syllabus/cse-2026-mains.md.
# Do not edit by hand: change the dataset or the importer and regenerate.
# source: owner = text supplied by the owner (a compilation of the UPSC notification), not fetched from UPSC.
# reviewed: false until the owner has checked a node against the official notification.
"""

# Paper start marker in the text -> (id, title, paper code). Subject headings are the compiler's own.
GS_PAPERS = {
    "GS-I": ("gs1", "GS Paper I", "GS1"),
    "GS-II": ("gs2", "GS Paper II", "GS2"),
    "GS-III": ("gs3", "GS Paper III", "GS3"),
    "GS-IV": ("gs4", "GS Paper IV", "GS4"),
}
# heading text at the start of a line -> (subject id, subject title)
SUBJECTS = {
    "gs1": [
        ("Art & Culture", "gs1.culture", "Art & Culture"),
        ("History (", "gs1.history", "History"),
        ("Indian Society", "gs1.society", "Indian Society"),
        ("Geography (", "gs1.geography", "Geography"),
    ],
    "gs2": [
        ("Polity & Constitution", "gs2.polity", "Polity & Constitution"),
        ("Governance", "gs2.governance", "Governance"),
        ("Social Justice", "gs2.socialjustice", "Social Justice"),
        ("International Relations", "gs2.ir", "International Relations"),
    ],
    "gs3": [
        ("Indian Economy", "gs3.economy", "Indian Economy"),
        ("Agriculture & Food", "gs3.agriculture", "Agriculture & Food"),
        ("Science & Technology", "gs3.scitech", "Science & Technology"),
        ("Environment, Bio-diversity", "gs3.environment", "Environment and Bio-diversity"),
        ("Disaster Management", "gs3.disaster", "Disaster Management"),
        ("Internal Security", "gs3.security", "Internal Security"),
    ],
    "gs4": [
        ("Official intro line", "gs4.ethics", "Ethics, Integrity and Aptitude"),
        ("Broad areas covered", "gs4.ethics", "Ethics, Integrity and Aptitude"),
    ],
}

_ROMAN = r"(?:i{1,3}|iv|v|vi{0,2}|vii)"
_GS_POINT = re.compile(r"^(\d+)\.\s+(\S.*)$")
_SOC_SECTION = re.compile(r"^(\d+)\.\s*(.+?)\s*:\s*$")
_SOC_ITEM = re.compile(r"^\(\s*([a-z])\s*\)\s*(.*)$")
_SOC_PART = re.compile(r"^([ABC])\.\s+(.+?)\s*:?\s*$")
_SOC_GROUP = re.compile(rf"^\(({_ROMAN})\)\s*(.+?)\s*:?\s*$")
_PAPER = re.compile(r"^PAPER\s*[–-]\s*(I{1,2})\s*$")


def _clean(text: str) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    for wrong, right in TYPO_FIXES.items():
        text = text.replace(wrong, right)
    return text


def _node(id_: str, title: str, kind: str, paper: str | None = None) -> dict:
    n: dict = {"id": id_, "title": title, "kind": kind}
    if paper:
        n["paper"] = paper
    n["source"] = "owner"
    n["reviewed"] = False
    return n


def _body(md: str) -> list[str]:
    parts = md.split("---\n", 2)
    text = parts[2] if len(parts) == 3 else md
    text = re.sub(r"<!-- page \d+ -->", "", text)
    return [ln.strip() for ln in text.splitlines()]


def _parse_gs(lines: list[str]) -> list[dict]:
    papers: list[dict] = []
    paper: dict | None = None
    subject: dict | None = None
    current: dict | None = None  # point being accumulated
    count = 0

    def flush() -> None:
        nonlocal current
        if current is not None and subject is not None:
            current["title"] = _clean(current["title"])
            subject["children"].append(current)
        current = None

    for ln in lines:
        if ln.startswith("OPTIONAL"):
            break
        m = re.match(r"^(GS-(?:I|II|III|IV)) — ", ln)
        if m:
            flush()
            pid, ptitle, code = GS_PAPERS[m.group(1)]
            paper = _node(pid, ptitle, "paper", code)
            paper["children"] = []
            papers.append(paper)
            subject = None
            count = 0
            continue
        if paper is None:
            continue
        if ln.startswith("Total official points"):
            flush()
            subject = None
            continue
        heading = next((h for h in SUBJECTS[paper["id"]] if ln.startswith(h[0])), None)
        if heading and not _GS_POINT.match(ln):
            flush()
            existing = next((s for s in paper["children"] if s["id"] == heading[1]), None)
            if existing is None:
                existing = _node(heading[1], heading[2], "subject")
                existing["children"] = []
                paper["children"].append(existing)
            subject = existing
            count = len(existing["children"])
            continue
        point = _GS_POINT.match(ln)
        if point and subject is not None:
            flush()
            count += 1
            label = "intro" if subject["id"] == "gs4.ethics" and not subject["children"] else f"p{count}"
            current = _node(f"{subject['id']}.{label}", point.group(2), "topic")
            continue
        if current is not None and ln:
            current["title"] += " " + ln
    flush()
    return papers


def _parse_sociology(lines: list[str]) -> list[dict]:
    start = next((i for i, ln in enumerate(lines) if ln.startswith("OPTIONAL")), None)
    if start is None:
        return []
    papers: list[dict] = []
    paper = section = group = item = None
    mode = ""

    def close_item() -> None:
        nonlocal item
        if item is not None:
            item["title"] = _clean(item["title"])
            item = None

    for ln in lines[start + 1 :]:
        pm = _PAPER.match(ln)
        if pm:
            close_item()
            n = len(pm.group(1))
            mode = f"P{n}"
            if n == 1:
                paper = _node("soc1", "Sociology Paper I: Fundamentals of Sociology", "paper", "SOC1")
            else:
                paper = _node(
                    "soc2", "Sociology Paper II: Indian Society: Structure and Change", "paper", "SOC2"
                )
            paper["children"] = []
            papers.append(paper)
            section = group = None
            continue
        if paper is None or not ln:
            continue
        if mode == "P1":
            sm = _SOC_SECTION.match(ln)
            if sm and not _SOC_ITEM.match(ln):
                close_item()
                section = _node(f"soc1.s{sm.group(1)}", _clean(sm.group(2)), "subject")
                section["children"] = []
                paper["children"].append(section)
                continue
            im = _SOC_ITEM.match(ln)
            if im and section is not None:
                close_item()
                kind = "thinker" if section["id"] == "soc1.s4" else "topic"
                item = _node(f"{section['id']}.{im.group(1)}", im.group(2), kind)
                section["children"].append(item)
                continue
        else:
            part = _SOC_PART.match(ln)
            if part and not _SOC_ITEM.match(ln):
                close_item()
                section = _node(f"soc2.{part.group(1).lower()}", _clean(part.group(2)), "subject")
                section["children"] = []
                paper["children"].append(section)
                group = None
                continue
            gm = _SOC_GROUP.match(ln)
            if gm and section is not None:
                close_item()
                group = _node(f"{section['id']}.{gm.group(1)}", _clean(gm.group(2)), "topic")
                group["children"] = []
                section["children"].append(group)
                continue
            im = _SOC_ITEM.match(ln)
            if im and group is not None:
                close_item()
                item = _node(f"{group['id']}.{im.group(1)}", im.group(2), "microtheme")
                group["children"].append(item)
                continue
        if item is not None:
            item["title"] += " " + ln
    close_item()
    return papers


def build_ontology(md: str) -> list[dict]:
    lines = _body(md)
    roots = _parse_gs(lines) + _parse_sociology(lines)
    if not roots or not any(r["id"] == "gs1" for r in roots):
        raise ValueError("This document does not contain the expected GS and Sociology syllabus structure.")
    return roots


def write_ontology(roots: list[dict], out_dir: Path) -> None:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    groups = {"gs1": ["gs1"], "gs2": ["gs2"], "gs3": ["gs3"], "gs4": ["gs4"], "sociology": ["soc1", "soc2"]}
    for name, ids in groups.items():
        nodes = [r for r in roots if r["id"] in ids]
        body = yaml.safe_dump({"version": 1, "nodes": nodes}, sort_keys=False, allow_unicode=True, width=110)
        (out_dir / f"{name}.yaml").write_text(HEADER + body, encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate ontology YAML from the syllabus Markdown.")
    ap.add_argument("markdown", type=Path)
    ap.add_argument("out_dir", type=Path)
    args = ap.parse_args(argv)
    roots = build_ontology(args.markdown.read_text(encoding="utf-8"))
    write_ontology(roots, args.out_dir)
    print(f"wrote {len(roots)} papers to {args.out_dir}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
